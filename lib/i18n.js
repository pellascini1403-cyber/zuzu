// Sistema de i18n de la app: 10 idiomas pedidos explícitamente (inglés,
// español, chino, japonés, coreano, portugués, ruso, francés, alemán y
// árabe). `LANGUAGES` alimenta a LanguageModal (código + nombre nativo,
// para que cada usuario reconozca su propio idioma en la lista aunque la
// interfaz esté en otro). `TRANSLATIONS` cubre el "chrome" visible de la
// app (títulos, labels de fila, botones) — con fallback a inglés si a
// algún idioma le falta una clave.
//
// Dos límites de alcance, a propósito, para no terminar mostrando una
// traducción parcial/engañosa:
// 1. Sin espejado RTL para árabe: cada modal de esta app usa posicionamiento
//    absoluto medido en píxeles contra una imagen de referencia — invertir
//    ese layout a RTL es un trabajo aparte, mucho más grande que traducir
//    texto. El árabe traduce el texto visible pero el layout se mantiene
//    LTR.
// 2. El contenido largo de FAQ/Terms of service/User policy (las preguntas
//    del FAQ y los párrafos legales de Terms/User policy) queda solo en
//    inglés — se tradujeron los títulos y toda la "chrome" corta de esos
//    tres modales, pero no ese cuerpo de texto extenso.
